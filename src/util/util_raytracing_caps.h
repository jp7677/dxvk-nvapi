#pragma once

#include "../nvapi_private.h"

namespace dxvk {
    inline std::string fromRaytracingCaps(const int32_t code) {
        static const std::map<int32_t, std::string> codes{
            MAP_ENUM_VALUE(NVAPI_D3D12_RAYTRACING_CAPS_TYPE_THREAD_REORDERING),
            MAP_ENUM_VALUE(NVAPI_D3D12_RAYTRACING_CAPS_TYPE_OPACITY_MICROMAP),
            MAP_ENUM_VALUE(NVAPI_D3D12_RAYTRACING_CAPS_TYPE_DISPLACEMENT_MICROMAP),
            MAP_ENUM_VALUE(NVAPI_D3D12_RAYTRACING_CAPS_TYPE_CLUSTER_OPERATIONS),
            MAP_ENUM_VALUE(NVAPI_D3D12_RAYTRACING_CAPS_TYPE_PARTITIONED_TLAS),
            MAP_ENUM_VALUE(NVAPI_D3D12_RAYTRACING_CAPS_TYPE_SPHERES),
            MAP_ENUM_VALUE(NVAPI_D3D12_RAYTRACING_CAPS_TYPE_LINEAR_SWEPT_SPHERES),
            MAP_ENUM_VALUE(NVAPI_D3D12_RAYTRACING_CAPS_TYPE_SHADER_IDENTIFIER_CAPTURE_REPLAY),
            MAP_ENUM_VALUE(NVAPI_D3D12_RAYTRACING_CAPS_TYPE_INVALID),
        };

        auto it = codes.find(code);
        return it != codes.end() ? it->second : "UNKNOWN_NVAPI_D3D12_RAYTRACING_CAPS_TYPE";
    }
}
